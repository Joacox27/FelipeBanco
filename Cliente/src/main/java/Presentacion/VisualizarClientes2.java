        private Object[] obtenerFila(int fila) {

        Object[] datos = new Object[modeloTabla.getColumnCount()];

        for (int columna = 0; columna < datos.length; columna++) {
            datos[columna] = modeloTabla.getValueAt(fila, columna);
        }

        return datos;
    }
    
    private void guardarEdicion(javax.swing.event.TableModelEvent evento) {

        if (actualizandoTabla
                || evento.getType() != javax.swing.event.TableModelEvent.UPDATE
                || evento.getFirstRow() == javax.swing.event.TableModelEvent.HEADER_ROW) {
            return;
        }

        int fila = evento.getFirstRow();

        if (fila < 0 || fila >= modeloTabla.getRowCount()) {
            return;
        }

        String documento = modeloTabla.getValueAt(fila, 0).toString();

        Object[] datosAnteriores = datosConfirmados.get(documento);

        if (datosAnteriores == null) {
            cargarClientes();
            return;
        }

        try {
            String nombre = modeloTabla.getValueAt(fila, 1).toString().trim();
            String apellido = modeloTabla.getValueAt(fila, 2).toString().trim();
            String fechaTexto = modeloTabla.getValueAt(fila, 3).toString().trim();
            String calle = modeloTabla.getValueAt(fila, 4).toString().trim();
            String numero = modeloTabla.getValueAt(fila, 5).toString().trim();
            String ciudad = modeloTabla.getValueAt(fila, 6).toString().trim();
            String telefono = modeloTabla.getValueAt(fila, 7).toString().trim();

            if (nombre.isEmpty() || apellido.isEmpty()
                    || fechaTexto.isEmpty() || calle.isEmpty()
                    || numero.isEmpty() || ciudad.isEmpty()) {
                throw new IllegalArgumentException(
                    "Los campos obligatorios no pueden quedar vacíos."
                );
            }

            java.time.LocalDate fechaNacimiento =
                java.time.LocalDate.parse(fechaTexto);

            Cliente clienteModificado = new Cliente(
                documento,
                nombre,
                apellido,
                fechaNacimiento,
                calle,
                numero,
                ciudad,
                telefono
            );

            Fachada.getInstancia().modificarCliente(clienteModificado);

            datosConfirmados.put(documento, obtenerFila(fila));

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Cliente modificado correctamente.",
                "FelipeBanco",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

        } catch (RuntimeException e) {

            actualizandoTabla = true;

            try {
                for (int columna = 0; columna < datosAnteriores.length; columna++) {
                    modeloTabla.setValueAt(
                        datosAnteriores[columna],
                        fila,
                        columna
                    );
                }
            } finally {
                actualizandoTabla = false;
            }

            javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage() == null
                    ? "No se pudo modificar el cliente."
                    : e.getMessage(),
                "Error al modificar",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }

