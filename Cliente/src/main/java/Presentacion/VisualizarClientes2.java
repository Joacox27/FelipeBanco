    private void configurarBuscador() {

        jTextField_buscar.getDocument().addDocumentListener(
            new DocumentListener() {

                @Override
                public void insertUpdate(DocumentEvent e) {
                    filtrarClientes();
                }

                @Override
                public void removeUpdate(DocumentEvent e) {
                    filtrarClientes();
                }

                @Override
                public void changedUpdate(DocumentEvent e) {
                    filtrarClientes();
                }
            }
        );
    }

    private void filtrarClientes() {

        String texto = jTextField_buscar.getText().trim();

        if (texto.isEmpty()) {

            ordenador.setRowFilter(null);

        } else {

            ordenador.setRowFilter(
                RowFilter.regexFilter(
                    "(?i)" + java.util.regex.Pattern.quote(texto)
                )
            );
        }

        actualizarContador();
    }

    private void cargarClientes() {

        actualizandoTabla = true;

        try {
            ArrayList<Cliente> lista =
                Fachada.getInstancia().mostrarClientes();

            modeloTabla.setRowCount(0);
            datosConfirmados.clear();

            for (Cliente c : lista) {

                Object[] fila = {
                    c.getDocumento(),
                    c.getNombre(),
                    c.getApellido(),
                    c.getFechaNacimiento(),
                    c.getCalle(),
                    c.getNumero(),
                    c.getCiudad(),
                    c.getTelefono()
                };

                modeloTabla.addRow(fila);

                datosConfirmados.put(
                    c.getDocumento(),
                    fila.clone()
                );
            }

            actualizarContador();

        } catch (RuntimeException e) {

            javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error al cargar clientes",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );

        } finally {
            actualizandoTabla = false;
        }
    }

    private void actualizarContador() {

        jLabel_cantidad.setText(
            "Clientes visibles: " + jTable1_display.getRowCount()
        );
    }

    private void eliminarClienteSeleccionado() {

        int filaSeleccionada =
            jTable1_display.getSelectedRow();

        if (filaSeleccionada == -1) {

            JOptionPane.showMessageDialog(
                this,
                "Seleccioná un cliente de la tabla.",
                "Sin selección",
                JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int filaModelo =
            jTable1_display.convertRowIndexToModel(filaSeleccionada);

        String documento =
            modeloTabla.getValueAt(filaModelo, 0).toString();

        int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Estás seguro de eliminar al cliente "
                + documento + "?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirmacion != JOptionPane.YES_OPTION) {
            return;
        }

        try {

            Fachada.getInstancia().eliminarCliente(documento);

            JOptionPane.showMessageDialog(
                this,
                "Cliente eliminado correctamente.",
                "FelipeBanco",
                JOptionPane.INFORMATION_MESSAGE
            );

            cargarClientes();

        } catch (RuntimeException e) {

            JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error al eliminar cliente",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }

    
