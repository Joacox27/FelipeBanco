    private void configurarTabla() {

        jTable_funcionarios.setModel(modeloTabla);

        ordenador = new javax.swing.table.TableRowSorter<>(modeloTabla);
        jTable_funcionarios.setRowSorter(ordenador);

        jTable_funcionarios.setSelectionMode(
            javax.swing.ListSelectionModel.SINGLE_SELECTION
        );

        jTable_funcionarios.setRowHeight(27);

        jTable_funcionarios.putClientProperty(
            "terminateEditOnFocusLost",
            Boolean.TRUE
        );
    }
    
    private void cargarFuncionarios() {

        actualizandoTabla = true;

        try {

            java.util.ArrayList<Logico.Funcionario> funcionarios =
                Logico.Fachada.getInstancia().mostrarFuncionarios();

            modeloTabla.setRowCount(0);
            datosConfirmados.clear();

            for (Logico.Funcionario f : funcionarios) {

                String sucursal = "";

                if (f.getSucursal() != null) {
                    sucursal = f.getSucursal().getNombre();
                }

                Object[] fila = {
                    f.getIdFuncionario(),
                    f.getNombre(),
                    f.getRol(),
                    f.getFechaIngreso(),
                    sucursal
                };

                modeloTabla.addRow(fila);

                datosConfirmados.put(
                    String.valueOf(f.getIdFuncionario()),
                    fila.clone()
                );
            }

            actualizarContador();

        } catch (RuntimeException e) {

            javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error al cargar funcionarios",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );

        } finally {
            actualizandoTabla = false;
        }
    }
    
    private void configurarBuscador() {

        jTextField_buscar.getDocument().addDocumentListener(
            new javax.swing.event.DocumentListener() {

                @Override
                public void insertUpdate(javax.swing.event.DocumentEvent e) {
                    filtrarFuncionarios();
                }

                @Override
                public void removeUpdate(javax.swing.event.DocumentEvent e) {
                    filtrarFuncionarios();
                }

                @Override
                public void changedUpdate(javax.swing.event.DocumentEvent e) {
                    filtrarFuncionarios();
                }
            }
        );
    }

    private void filtrarFuncionarios() {

        String texto = jTextField_buscar.getText().trim();

        if (texto.isEmpty()) {
            ordenador.setRowFilter(null);
        } else {
            ordenador.setRowFilter(
                javax.swing.RowFilter.regexFilter(
                    "(?i)" + java.util.regex.Pattern.quote(texto)
                )
            );
        }

        actualizarContador();
    }

    private void actualizarContador() {

        jLabel_cantidad.setText(
            "Funcionarios visibles: " + jTable_funcionarios.getRowCount()
        );
    }
    
    private void guardarEdicion(
            javax.swing.event.TableModelEvent evento) {

        if (actualizandoTabla
                || evento.getType()
                    != javax.swing.event.TableModelEvent.UPDATE
                || evento.getFirstRow()
                    == javax.swing.event.TableModelEvent.HEADER_ROW) {
            return;
        }

        int fila = evento.getFirstRow();

        if (fila < 0 || fila >= modeloTabla.getRowCount()) {
            return;
        }

        String id = String.valueOf(modeloTabla.getValueAt(fila, 0));
        Object[] anteriores = datosConfirmados.get(id);

        if (anteriores == null) {
            cargarFuncionarios();
            return;
        }

        try {

            String nombre = String.valueOf(
                modeloTabla.getValueAt(fila, 1)
            ).trim();

            String rol = String.valueOf(
                modeloTabla.getValueAt(fila, 2)
            ).trim();

            String nombreSucursal = String.valueOf(
                modeloTabla.getValueAt(fila, 4)
            ).trim();

            if (nombre.isEmpty() || rol.isEmpty()
                    || nombreSucursal.isEmpty()) {
                throw new IllegalArgumentException(
                    "El nombre, el rol y la sucursal son obligatorios."
                );
            }

            Logico.Fachada.getInstancia().modificarFuncionario(
                id,
                nombre,
                nombreSucursal,
                rol
            );

            datosConfirmados.put(id, obtenerFila(fila));

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Funcionario modificado correctamente.",
                "FelipeBanco",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

        } catch (RuntimeException e) {

            actualizandoTabla = true;

            try {
                for (int columna = 0; columna < anteriores.length; columna++) {
                    modeloTabla.setValueAt(
                        anteriores[columna],
                        fila,
                        columna
                    );
                }
            } finally {
                actualizandoTabla = false;
            }

            javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage() == null
                    ? "No se pudo modificar el funcionario."
                    : e.getMessage(),
                "Error al modificar",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }
    


    private Object[] obtenerFila(int fila) {

        Object[] datos = new Object[modeloTabla.getColumnCount()];

        for (int columna = 0; columna < datos.length; columna++) {
            datos[columna] = modeloTabla.getValueAt(fila, columna);
        }

        return datos;
    }
    
    private void jButton_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_eliminarActionPerformed

        int filaSeleccionada = jTable_funcionarios.getSelectedRow();

        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Seleccioná un funcionario de la tabla.",
                "Sin selección",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int filaModelo = jTable_funcionarios.convertRowIndexToModel(
            filaSeleccionada
        );

        String id = String.valueOf(
            modeloTabla.getValueAt(filaModelo, 0)
        );

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Querés eliminar al funcionario con ID " + id + "?",
            "Confirmar eliminación",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {

            Logico.Fachada.getInstancia().eliminarFuncionario(id);

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Funcionario eliminado correctamente.",
                "FelipeBanco",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            cargarFuncionarios();

        } catch (RuntimeException e) {

            javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error al eliminar",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
        
    }//GEN-LAST:event_jButton_eliminarActionPerformed

